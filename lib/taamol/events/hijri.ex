  # day 1 of 1471/1, which closes the last month in the table
  @table_end ~D[2048-10-09]

  # newest first: [{first_day, year, month}, ...]
  @month_starts (for {year, dates} <- @umm_al_qura, {date, i} <- Enum.with_index(dates, 1) do
                   {Date.from_iso8601!(date), year, i}
                 end)
                |> Enum.sort_by(&elem(&1, 0), {:desc, Date})

  {table_start, _, _} = List.last(@month_starts)
  @table_start table_start

  @epoch ~D[0622-07-19]

  @doc "Converts a Gregorian date to `{year, month, day}` in the Hijri calendar."
  @spec from_date(Date.t()) :: hijri()
  def from_date(%Date{} = date) do
    date = Date.add(date, -adjustment())

    if in_table?(date) do
      {start, year, month} =
        Enum.find(@month_starts, fn {start, _, _} -> Date.compare(start, date) != :gt end)

      {year, month, Date.diff(date, start) + 1}
    else
      tabular_from_date(date)
    end
  end

  @doc "Converts a Hijri date to a Gregorian `Date`."
  @spec to_date(integer(), 1..12, 1..30) :: Date.t()
  def to_date(year, month, day) do
    base =
      case month_start(year, month) do
        %Date{} = start -> Date.add(start, day - 1)
        nil -> Date.add(@epoch, tabular_days(year, month, day))
      end

    Date.add(base, adjustment())
  end

  @doc "Number of days in a Hijri month (29 or 30)."
  @spec month_length(integer(), 1..12) :: 29 | 30
  def month_length(year, month) do
    {next_year, next_month} = if month == 12, do: {year + 1, 1}, else: {year, month + 1}

    case {month_start(year, month), month_start(next_year, next_month)} do
      {%Date{} = a, %Date{} = b} -> Date.diff(b, a)
      {%Date{} = a, nil} when year == 1470 and month == 12 -> Date.diff(@table_end, a)
      _ -> tabular_days(next_year, next_month, 1) - tabular_days(year, month, 1)
    end
  end

  defp month_start(year, month) do
    Enum.find_value(@month_starts, fn
      {start, ^year, ^month} -> start
      _ -> nil
    end)
  end

  defp in_table?(date),
    do: Date.compare(date, @table_start) != :lt and Date.compare(date, @table_end) == :lt

  defp adjustment, do: Application.get_env(:taamol, :hijri_adjustment_days, 0)

  # --- arithmetic (tabular) Islamic calendar, civil epoch ---------------------

  defp tabular_days(year, month, day) do
    day + ceil(29.5 * (month - 1)) + (year - 1) * 354 + Integer.floor_div(3 + 11 * year, 30) - 1
  end

  defp tabular_from_date(date) do
    days = Date.diff(date, @epoch)
    year = Integer.floor_div(30 * days + 10_646, 10_631)
    month = min(12, ceil((days - 29 - tabular_days(year, 1, 1)) / 29.5) + 1)
    {year, month, days - tabular_days(year, month, 1) + 1}
  end
end
