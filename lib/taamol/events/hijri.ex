  Gregorian ⇄ Hijri (Islamic) date conversion.

  Uses the Umm al-Qura calendar for 1440–1470 AH (Sep 2018 – Sep 2048): the
  first day of every month, generated from ICU's `islamic-umalqura` calendar,
  is embedded below. Outside that range it falls back to the arithmetic
  (tabular) Islamic calendar, which can be off by a day or two.

  Moon sighting can put local dates a day earlier or later than Umm al-Qura.
  Shift every Hijri date with:

      config :taamol, :hijri_adjustment_days, 1   # Hijri dates fall a day later
  """

